"""
================================================================================
文件作用：所有数据库表的公共基类，外加一个取当前时间的小工具
================================================================================

这是全项目最小的文件之一，但每张表都依赖它。

--------------------------------------------------------------------------------
本文件的代码块：
--------------------------------------------------------------------------------
  第 1 块  Base       所有表类的父类
  第 2 块  utcnow()   取当前时间（带 UTC 时区）
================================================================================
"""

from __future__ import annotations

from datetime import datetime, timezone
from sqlalchemy.orm import DeclarativeBase


# ── 第 1 块：所有表的父类 ──────────────────────────────────────────────────
class Base(DeclarativeBase):
    """Async-friendly declarative base.

    models.py 里每个表类都写成 `class Xxx(Base)`，继承它之后 SQLAlchemy 才
    知道"这个类代表一张表"，才会去收集它的字段、生成建表语句。

    它还起到"登记册"的作用：所有继承过它的表都被记录在 Base.metadata 里。
    测试里的 `Base.metadata.create_all` 就是靠这个一次性建出全部 11 张表的
    （见 tests/conftest.py）。

    类体里只有一行文档字符串、没有任何代码，是故意的——
    我们不需要给所有表加公共字段，只需要这个"共同的父亲"这个身份。
    """


# ── 第 2 块：取当前时间 ────────────────────────────────────────────────────
def utcnow() -> datetime:
    """返回当前时间，带 UTC 时区。

    ★ 为什么不用更短的 datetime.now()：
      datetime.now() 返回的是"不带时区信息"的本地时间。存进数据库后，
      谁也不知道那个 "14:30" 到底是北京时间还是伦敦时间。服务器换个时区、
      或者本地开发和生产环境时区不同，数据就对不上了。
      带上 timezone.utc 之后，存的永远是世界统一时间，显示的时候再转成
      本地时间，怎么折腾都不会错。

    ★ 为什么要包成一个函数，而不是直接写 datetime.now(timezone.utc)：
      models.py 里很多字段写的是 `default=utcnow`——注意没有括号。
      传的是"函数本身"，SQLAlchemy 会在每次新建记录时才去调用它，
      拿到的是那一刻的时间。
      如果写成 `default=datetime.now(timezone.utc)`（带括号），那就是在
      程序启动的那一瞬间算出一个固定值，之后所有记录的时间戳都一样，
      全是服务器启动时间——这是个很隐蔽的经典 bug。
    """
    return datetime.now(timezone.utc)
