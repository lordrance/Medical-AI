"""
================================================================================
文件作用：★ 四种处理方式的定义 —— 整个实验要观测的那个变量就是它
================================================================================

医生看完 AI 草稿后必须四选一。这个选择就是研究的「因变量」——
所有分析最终都围绕它展开。

这个文件定义了三样东西：
  * 四种方式的机器取值（存数据库、写代码用的英文名）
  * 对应的中文标签（界面和导出报表显示用）
  * 问卷 PDF 里规定的术语（论文编码表用）

★ 为什么三套名字：代码里要用英文（不能用中文当变量名）、
  界面要显示中文、论文有自己规定的用词。三者必须能一一对应，
  所以在这里集中维护，而不是散落在各处各写各的。

--------------------------------------------------------------------------------
本文件的代码块：
--------------------------------------------------------------------------------
  第 1 块  SelectedAction        ★ 四种处理方式
  第 2 块  ACTION_LABEL_ZH       英文取值 → 界面中文标签
  第 3 块  LOG_FINAL_ACTION_PDF  英文取值 → 问卷 PDF 用词
  第 4 块  EscalateSubtype       选「上报」后的细分类型
================================================================================
"""

from __future__ import annotations

from enum import Enum


# ── 第 1 块：四种处理方式 ★ ────────────────────────────────────────────────
class SelectedAction(str, Enum):
    """四种处理方式。

    Enum（枚举）表示"取值只能是下面列的这几个之一"。好处是写错会立刻报错，
    而不是把一个拼错的字符串静默地存进数据库。

    同时继承 str 是个常用技巧：这样枚举值可以直接当字符串用
    （能比较、能存数据库、能转 JSON），不用每次都写 .value。

    ★ 这些字符串会写进数据库、导出到 CSV、对应论文的编码表。
      改动等于让已收集的 296 条作答数据对不上号。绝对不要改。
    """

    send_as_is = "send_as_is"                    # 原样发送：完全信任 AI
    edit_then_send = "edit_then_send"            # 改一改再发：部分信任
    discard_and_rewrite = "discard_and_rewrite"  # 弃用重写：基本不信任
    escalate = "escalate"                        # 上报：认为超出消息回复的范围


# ── 第 2 块：界面用的中文标签 ──────────────────────────────────────────────
# Chinese-localized labels for the four actions, exposed via /api/meta or copied
# into the frontend i18n dict. Keeping them server-side ensures admin export
# uses identical labels.
#
# 中文：把机器取值翻译成人看的中文。
# ★ 为什么后端也要存一份（前端 i18n 里明明也有）：
#   管理后台导出的 CSV 是后端生成的，如果后端不知道中文标签，
#   导出的报表里就只有 "send_as_is" 这种英文，你还得自己对照着改。
#   两边保持一致，导出的表格才是能直接放进论文的。
ACTION_LABEL_ZH: dict[str, str] = {
    "send_as_is": "原样发送",
    "edit_then_send": "编辑后发送",
    "discard_and_rewrite": "弃用并重写",
    "escalate": "升级处理",
}


# ── 第 3 块：问卷 PDF 规定的用词 ───────────────────────────────────────────
# 问卷 7.0：`log_final_action` 类别取值（与 PDF「1=直接发送…」表格用语一致；UI 仍可用「原样发送」）
#
# 中文：和上面那张表看着很像，但用词不同——注意第一个是「直接发送」
# 而不是「原样发送」。
#
# ★ 这不是笔误。界面上给医生看的措辞（原样发送）和论文编码表里的术语
#   （直接发送）本来就不一样，两边各自沿用各自的习惯。
#   这张表用于往 actions.log_final_action 列里写值，
#   保证导出的数据能直接对上论文附录的编码表。
LOG_FINAL_ACTION_PDF: dict[str, str] = {
    "send_as_is": "直接发送",
    "edit_then_send": "编辑后发送",
    "discard_and_rewrite": "弃用并重写",
    "escalate": "升级处理",
}


# ── 第 4 块：上报的细分类型 ────────────────────────────────────────────────
class EscalateSubtype(str, Enum):
    """选了「上报」之后，再细分成哪一种。

    医生除了选这个类型，还要填一段自由文本说明理由
    （api/action.py 里有校验：选上报必须写理由）。
    """

    urgent_evaluation = "urgent_evaluation"  # 需要紧急面诊评估
    call_patient = "call_patient"            # 需要电话联系患者
    other = "other"                          # 其他情况
