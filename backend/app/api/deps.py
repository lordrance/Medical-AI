"""
================================================================================
文件作用：定义"依赖" —— 每个接口开工前，框架自动帮它准备好的东西
================================================================================

"依赖"（dependency）是 FastAPI 的一个机制。你在接口函数的参数里写：

    async def 某接口(db: AsyncSession = Depends(db_session)):

意思就是："我需要一个数据库会话，请框架在调用我之前准备好塞进 db 参数"。
框架会自动调用 db_session()、拿到会话、传进来，等接口跑完再自动回收。

好处是接口函数里不用写任何"开连接、用完关连接"的样板代码，
也不会忘记关——忘关会把连接池耗光，全站卡死。

--------------------------------------------------------------------------------
本文件的代码块：
--------------------------------------------------------------------------------
  第 1 块  db_session()   唯一的一个依赖：发一个数据库会话
================================================================================
"""

from __future__ import annotations

from collections.abc import AsyncIterator

from sqlalchemy.ext.asyncio import AsyncSession

from app.db.session import get_db


# ── 第 1 块：数据库会话依赖 ──────────────────────────────────────────────────
async def db_session() -> AsyncIterator[AsyncSession]:
    """给当前这个 HTTP 请求发一个数据库会话。

    这个函数只是对 db/session.py 里 get_db() 的一层转发，本身不做别的。
    为什么要多这一层：所有接口都统一从 app.api.deps 导入依赖，
    将来如果要给所有接口的数据库会话加点共同逻辑（比如统计每个请求
    查了几次库、或者按请求路由到不同的库），只要改这一个文件就行，
    不用去改二十几个接口文件。
    """
    # async for ... yield 的写法把 get_db() 产出的会话原样往外传。
    # 它同时也把 get_db 里的收尾逻辑（出错回滚、用完归还连接池）
    # 一并继承下来了。
    async for s in get_db():
        yield s
