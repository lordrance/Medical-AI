"""
================================================================================
文件作用：健康检查接口 —— 用来确认"后端还活着吗"
================================================================================

打开 https://medraftlab.com/healthz，如果看到 {"ok":true, ...} 就说明后端正常。
网站出问题时，这是你第一个该看的地方：
    能打开 → 后端活着，问题在前端或网络
    打不开 → 后端挂了或者容器没起来

有三个地方会用到它：
  1. Docker 每 30 秒自动调一次，连续失败会把容器标记成"不健康"
  2. Caddy（反向代理）的转发规则里单独放行了这个路径
  3. 你自己排查问题的时候

★ 它故意不需要密码：返回的只有版本号和几个配置开关，不含任何研究数据。
★ 它故意不查数据库：数据库慢的时候，健康检查还应该秒回。否则 Docker 会
   误判容器已死并重启它，本来只是慢，重启后变成彻底中断，雪上加霜。

--------------------------------------------------------------------------------
本文件的代码块：
--------------------------------------------------------------------------------
  第 1 块  router      路由器（注意这个没有前缀，所以网址就是 /healthz）
  第 2 块  healthz()   返回一小包状态信息
================================================================================
"""

from __future__ import annotations

from fastapi import APIRouter

from app.core.config import get_settings


# ── 第 1 块：路由器 ──────────────────────────────────────────────────────────
# 注意这里没写 prefix=。别的文件都写了（比如 /api/session），
# 这里不写是因为健康检查的网址就是根目录下的 /healthz，不在 /api 下面。
router = APIRouter()


# ── 第 2 块：健康检查函数 ────────────────────────────────────────────────────
# tags=["meta"] 只影响自动生成的接口文档，把它归到"元信息"那一组。
@router.get("/healthz", tags=["meta"])
async def healthz() -> dict:
    """GET /healthz —— 返回后端的基本状态。"""
    # 读配置。get_settings 内部有缓存，反复调用不会反复读文件。
    settings = get_settings()

    # 直接拼一个字典返回，FastAPI 会自动转成 JSON。
    return {
        # 固定为 true。能返回这个字典本身就说明服务在跑。
        "ok": True,
        # 应用名字，固定值，用来确认"我连的确实是这个项目"。
        "appName": settings.APP_NAME,
        # 版本号。部署后看这里能确认新版本有没有生效。
        "appVersion": settings.APP_VERSION,
        # 运行环境：production（生产）/ development（开发）/ test（测试）。
        # 如果生产环境这里显示 development，说明配置没注入进去，是个隐患。
        "env": settings.APP_ENV,
        # 当前用哪个 AI 供应商。V4 生产环境应该是 "disabled"。
        "llmProvider": settings.LLM_PROVIDER,
        # AI 是否启用。llm_enabled 是配置类里的一个计算属性，
        # 内容就是"LLM_PROVIDER 不等于 disabled"。
        "llmEnabled": settings.llm_enabled,
    }
