"""
================================================================================
文件作用：★ 算「编辑距离」—— 医生把 AI 草稿改了多少
================================================================================

这是本研究最重要的连续型指标之一。医生提交答案时（见 api/action.py），
会拿 AI 的原始草稿和医生的最终定稿做一次比对，得出一个数字：

    0     一个字都没改  →  完全照搬 AI
    很小  只动了标点或个别词  →  走过场式的修改
    很大  大幅重写  →  基本不信任 AI

★ 单看这个数字还不够，要配合"这道题的 AI 草稿有没有埋错"一起看：
    有错 + 距离 0     → 危险：错误被原封不动发给了患者
    有错 + 距离很大   → 好：医生发现问题并改了
    没错 + 距离很大   → 过度谨慎，或者改错了方向

--------------------------------------------------------------------------------
本文件的代码块：
--------------------------------------------------------------------------------
  第 1 块  levenshtein()   唯一的一个函数
================================================================================
"""

from __future__ import annotations


# ── 第 1 块：编辑距离 ──────────────────────────────────────────────────────
def levenshtein(a: str, b: str) -> int:
    """Character-level Levenshtein edit distance, O(n*m) time, O(min(n,m)) space.

    ★ 大白话：算「把 a 变成 b，最少需要改几个字符」。
    允许的操作有三种，每种算一步：
        插入一个字符、删除一个字符、替换一个字符

    例子（中文按字算，一个汉字算一个字符）：
        "你好吗" → "你好呀"   = 1  （替换一个字）
        "你好"   → "你好吗"   = 1  （插入一个字）
        "你好吗" → "吗好你"   = 2  （替换首尾两个字）

    这个算法是 1965 年的经典算法，名字来自发明者 Levenshtein。
    """
    # ---- 三个快速返回，省得走完整算法 ----
    if a == b:
        return 0            # 一模一样，距离是 0
    if not a:
        return len(b)       # 一边是空的 → 要插入另一边的全部字符
    if not b:
        return len(a)       # 同上，只是方向相反

    # 保证 a 是较长的那个。
    # 为什么：下面的"滚动数组"长度是 min(n,m)+1，让短的那个当列，
    # 占的内存最少。距离本身是对称的（a→b 和 b→a 一样远），交换无害。
    if len(a) < len(b):
        a, b = b, a

    n, m = len(a), len(b)

    # ---- 核心：动态规划 ----
    # 标准做法是建一个 n×m 的表格，格子 [i][j] 表示
    # "把 a 的前 i 个字符变成 b 的前 j 个字符，最少要几步"。
    #
    # ★ 但这里只保留两行，不建整张表（这个优化叫「滚动数组」）：
    #   算第 i 行时只用得到第 i-1 行，更早的行再也用不上了。
    #   医生的回复可能上千字，完整表格要占好几 MB，两行只要几 KB。
    #
    # prev = 上一行的结果，curr = 正在算的这一行。
    #
    # 第 0 行的含义：把"空字符串"变成 b 的前 j 个字符，需要插入 j 次。
    # 所以第 0 行就是 [0, 1, 2, 3, ...]，正好是 range(m+1)。
    prev = list(range(m + 1))
    curr = [0] * (m + 1)   # 先占好位置，值待会儿填

    # 逐行填表。i 从 1 数到 n，代表"a 的前 i 个字符"。
    for i in range(1, n + 1):
        # 每行的第 0 个格子：把 a 的前 i 个字符变成空字符串，要删 i 次。
        curr[0] = i
        # 取出 a 的第 i 个字符。减 1 是因为下标从 0 开始。
        ca = a[i - 1]

        for j in range(1, m + 1):
            # 这两个字符一样就不花代价，不一样就算一次"替换"。
            cost = 0 if ca == b[j - 1] else 1
            # 三种走法取最省的那个：
            curr[j] = min(
                prev[j] + 1,          # 从上面来：删掉 a 的这个字符
                curr[j - 1] + 1,      # 从左边来：插入 b 的这个字符
                prev[j - 1] + cost,   # 从左上来：替换（字符相同时免费）
            )

        # 这一行算完了。交换两行：下一轮它就成了"上一行"。
        # 用交换而不是新建列表，避免每轮都重新分配内存。
        # 注意 curr 现在指向的是上上行的旧数据，但下一轮开头会全部覆盖掉，
        # 所以不用清空。
        prev, curr = curr, prev

    # 循环结束后，结果在 prev 里（因为最后交换过一次）。
    # prev[m] 就是"把整个 a 变成整个 b"的最小步数。
    return prev[m]
