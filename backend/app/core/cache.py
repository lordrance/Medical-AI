"""
================================================================================
文件作用：内存缓存 —— 把题目这类"永远不变"的数据存在内存里，不用反复查库
================================================================================

缓存的是什么：题目内容、题目顺序模板。这些数据是程序启动时从 JSON 文件灌进
数据库的，运行过程中一个字都不会变。

为什么需要：`GET /api/case/{id}` 是全系统最热的接口——每位医生要调 9 次
（1 道练习 + 8 道正式）。100 个人同时答题就是 900 次查询，而查回来的内容
每次都一模一样。缓存之后，除了第一次，其余全部直接读内存。

--------------------------------------------------------------------------------
★ 三个必须知道的注意事项
--------------------------------------------------------------------------------
  1. 缓存是**每个进程各存一份**的。生产环境跑 4 个 gunicorn 进程，
     所以同一份数据在内存里有 4 份。这没关系，反正是只读数据。

  2. 缓存**永不过期**。所以改了 cases.json 并重新 seed 之后，
     ★ 必须重启后端，否则老进程还在发旧题目。

  3. 测试里每个用例之间必须调 invalidate()。因为这个字典是模块级的，
     活得比每个测试的临时数据库还久，不清的话上个测试缓存的题目会
     "穿越"到下个测试里（见 tests/conftest.py）。

--------------------------------------------------------------------------------
为什么不用加锁
--------------------------------------------------------------------------------
每个 gunicorn 进程内部是单线程的事件循环，不存在两个线程同时写同一个字典。
而且就算两个请求都去填缓存，填进去的也是一模一样的只读数据，覆盖谁都无所谓。

--------------------------------------------------------------------------------
本文件的代码块：
--------------------------------------------------------------------------------
  第 1 块  _cache        缓存本体，就是一个全局字典
  第 2 块  get()         取缓存
  第 3 块  set()         存缓存
  第 4 块  invalidate()  清缓存
================================================================================
"""

from __future__ import annotations

from typing import Any


# ── 第 1 块：缓存本体 ──────────────────────────────────────────────────────
# 就是一个普通的全局字典。键是我们自己约定的字符串：
#     "case:case_01"    某道题的内容
#     "templates"       全部 4 套题目顺序
#     "practice_case"   练习题
# 值的类型五花八门（有 Pydantic 对象、有数据库对象列表），所以标成 Any。
#
# 名字前面的下划线是 Python 的约定：表示"这是内部实现，别从外面直接碰"。
_cache: dict[str, Any] = {}


# ── 第 2 块：取缓存 ────────────────────────────────────────────────────────
def get(key: str) -> Any | None:
    """Return the cached value or None.

    中文：取缓存。没存过就返回 None，调用方据此决定要不要去查数据库。

    用 dict.get() 而不是 _cache[key]：后者取不到会抛 KeyError，
    前者取不到安静地返回 None，正好符合"没有就去查库"的用法。
    """
    return _cache.get(key)


# ── 第 3 块：存缓存 ────────────────────────────────────────────────────────
def set(key: str, value: Any) -> None:
    """Store a value in the cache.

    中文：存缓存。

    ★ 这个函数名和 Python 内置的 set()（集合类型）撞名了。
    所以调用方都写成：
        from app.core.cache import get as cache_get, set as cache_set
    改个名字用，避免在那个文件里把内置的 set() 遮住。
    """
    _cache[key] = value


# ── 第 4 块：清缓存 ────────────────────────────────────────────────────────
def invalidate(key: str | None = None) -> None:
    """Remove a key, or clear all (for testing).

    中文：清缓存。传键名就只清那一个，不传参数就全清。

    ★ 改了题目内容后可以调它，但更保险的做法是直接重启后端——
    因为要清的是**所有 4 个进程**的缓存，而一次 HTTP 请求只能清到
    其中一个进程的。
    """
    if key is not None:
        # pop 的第二个参数是"取不到时的默认值"。给了 None 就表示
        # "键不存在也别报错"，让这个函数可以放心地重复调用。
        _cache.pop(key, None)
    else:
        _cache.clear()
